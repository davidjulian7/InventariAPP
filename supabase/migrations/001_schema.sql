-- RLS POLICIES
-- ============================================================

-- Stores: solo admin puede modificar, todos ven su tienda
create policy "Users can view their store" on public.stores
  for select using (
    id in (select store_id from public.user_profiles where id = auth.uid())
  );

-- Products: multi-tenant por store
create policy "Users can view products from their store" on public.products
  for select using (
    store_id in (select store_id from public.user_profiles where id = auth.uid())
  );

create policy "Users can insert products" on public.products
  for insert with check (
    store_id in (select store_id from public.user_profiles where id = auth.uid())
  );

create policy "Users can update products" on public.products
  for update using (
    store_id in (select store_id from public.user_profiles where id = auth.uid())
  );

-- Sales
create policy "Users can view their store sales" on public.sales
  for select using (
    store_id in (select store_id from public.user_profiles where id = auth.uid())
  );

create policy "Users can insert sales" on public.sales
  for insert with check (
    store_id in (select store_id from public.user_profiles where id = auth.uid())
  );

-- Sale items
create policy "Users can view sale items" on public.sale_items
  for select using (
    venta_id in (select id from public.sales where store_id in (select store_id from public.user_profiles where id = auth.uid()))
  );

create policy "Users can insert sale items" on public.sale_items
  for insert with check (
    venta_id in (select id from public.sales where store_id in (select store_id from public.user_profiles where id = auth.uid()))
  );

-- Inventory movements
create policy "Users can view movements" on public.inventory_movements
  for select using (
    store_id in (select store_id from public.user_profiles where id = auth.uid())
  );

create policy "Users can insert movements" on public.inventory_movements
  for insert with check (
    store_id in (select store_id from public.user_profiles where id = auth.uid())
  );

-- Categories
create policy "Users can view categories" on public.categories
  for select using (
    store_id in (select store_id from public.user_profiles where id = auth.uid())
  );

-- Suppliers
create policy "Users can view suppliers" on public.suppliers
  for select using (
    store_id in (select store_id from public.user_profiles where id = auth.uid())
  );
